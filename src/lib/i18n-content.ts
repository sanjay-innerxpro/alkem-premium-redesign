const getPath = (obj: unknown, path: string) =>
  path
    .split(".")
    .reduce<unknown>(
      (o, k) => (o == null ? undefined : (o as Record<string, unknown>)[k]),
      obj,
    );
function setPath(obj: Record<string, unknown>, path: string, value: string) {
  const keys = path.split(".");
  let o = obj;
  for (const k of keys.slice(0, -1)) o = o[k] as Record<string, unknown>;
  o[keys[keys.length - 1]] = value;
}

export function localizeSettings(s: Settings, lang: Lang): Settings {
  const pack = packs[lang];
  if (!pack) return s;
  const out = structuredClone(s);
  for (const [path, text] of Object.entries(pack.settings))
    if (getPath(s, path) === getPath(defaultSettings, path))
      setPath(out as unknown as Record<string, unknown>, path, text);
  return out;
}

